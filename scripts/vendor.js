// Copies third-party browser assets from node_modules into src/vendor so the
// app runs fully offline. Run with `npm run vendor` after upgrading a package.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const nm = (...p) => path.join(root, 'node_modules', ...p);
const out = path.join(root, 'src', 'vendor');
const fontsOut = path.join(out, 'fonts');

fs.mkdirSync(fontsOut, { recursive: true });

const copies = [
  [nm('chart.js', 'dist', 'chart.umd.min.js'), path.join(out, 'chart.umd.min.js')],
  [nm('lucide', 'dist', 'umd', 'lucide.min.js'), path.join(out, 'lucide.min.js')],
];

const fonts = [
  { family: 'Inter', pkg: 'inter', weight: '100 900' },
  { family: 'Space Grotesk', pkg: 'space-grotesk', weight: '300 700' },
];

// Same subsets/ranges as @fontsource-variable; latin-ext is needed for Turkish (ğ, ş, ı, İ).
const subsets = {
  'latin-ext': 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF',
  latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
};

let fontsCss = '/* Generated by scripts/vendor.js — do not edit. */\n';
for (const f of fonts) {
  for (const [subset, range] of Object.entries(subsets)) {
    const file = `${f.pkg}-${subset}-wght-normal.woff2`;
    copies.push([nm('@fontsource-variable', f.pkg, 'files', file), path.join(fontsOut, file)]);
    fontsCss += `@font-face {
  font-family: '${f.family}';
  font-style: normal;
  font-display: swap;
  font-weight: ${f.weight};
  src: url(./${file}) format('woff2-variations');
  unicode-range: ${range};
}
`;
  }
}

for (const [from, to] of copies) {
  fs.copyFileSync(from, to);
  console.log('vendored', path.relative(root, to));
}
fs.writeFileSync(path.join(fontsOut, 'fonts.css'), fontsCss);
console.log('wrote src/vendor/fonts/fonts.css');
